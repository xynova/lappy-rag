# requires-python = ">=3.11"
# ///
"""Generate docker/compose.mounts.yml with per-project bind mounts.

Reads all enabled bundle configs from configs/bundles/ (same walk rules as the
Go registry — skips directories ending with .example) and writes
docker/compose.mounts.yml as a Compose override with one bind mount per enabled
project whose host path exists on disk.

Host path:      ${CONTENT_ROOT_BASE}/<project-id>  (from .env or environment)
Container path: /content/projects/<project-id>     (always derived from id)

Usage:
    uv run scripts/gen_compose_mounts.py
"""

import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUNDLES_DIR = ROOT / "configs" / "bundles"
OUT_FILE = ROOT / "docker" / "compose.mounts.yml"
ENV_FILE = ROOT / "docker" / "env" / ".env"
CONTENT_PROJECTS_ROOT = "/content/projects"


def load_env_file(path: Path) -> dict[str, str]:
    env: dict[str, str] = {}
    if not path.exists():
        return env
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, val = line.partition("=")
        env[key.strip()] = val.strip()
    return env


def expand_vars(value: str, file_env: dict[str, str]) -> str:
    merged = {**file_env, **os.environ}
    for k, v in merged.items():
        value = value.replace(f"${{{k}}}", v)
    return value


def parse_bundle_id(text: str) -> str | None:
    m = re.search(r"^id:\s*(.+)$", text, re.MULTILINE)
    return m.group(1).strip() if m else None


def parse_bundle_host(text: str) -> str | None:
    """Extract paths.volume.host from bundle yaml text, or None if absent."""
    m = re.search(r"^\s+host:\s*(.+)$", text, re.MULTILINE)
    return m.group(1).strip() if m else None


def parse_bundle_enabled(text: str) -> bool:
    m = re.search(r"^enabled:\s*(.+)$", text, re.MULTILINE)
    return m.group(1).strip().lower() == "true" if m else False


def load_enabled_projects() -> list[tuple[str, str]]:
    """Return list of (project_id, raw_host_template) for enabled projects."""
    results: list[tuple[str, str]] = []
    for yaml_file in sorted(BUNDLES_DIR.rglob("*.yaml")):
        rel_parts = yaml_file.relative_to(BUNDLES_DIR).parts
        if any(part.endswith(".example") for part in rel_parts):
            continue
        try:
            text = yaml_file.read_text(encoding="utf-8")
        except Exception as exc:
            print(f"WARN: skipping {yaml_file.name}: {exc}", file=sys.stderr)
            continue
        if not parse_bundle_enabled(text):
            continue
        pid = parse_bundle_id(text)
        if not pid:
            continue
        host_tpl = parse_bundle_host(text)  # may be None
        results.append((pid, host_tpl or ""))
    return results


def main() -> None:
    file_env = load_env_file(ENV_FILE)
    content_root = expand_vars("${CONTENT_ROOT_BASE}", file_env).strip()
    if not content_root:
        print("ERROR: CONTENT_ROOT_BASE is not set in .env or environment", file=sys.stderr)
        sys.exit(1)

    projects = load_enabled_projects()
    if not projects:
        print("WARN: no enabled projects found — compose.mounts.yml will have no content mounts.")

    lines: list[str] = []
    skipped: list[str] = []

    for pid, host_tpl in projects:
        # Use explicit host from bundle if set, otherwise derive from CONTENT_ROOT_BASE/<id>.
        if host_tpl:
            host = expand_vars(host_tpl, file_env).strip()
        else:
            host = str(Path(content_root) / pid)
        container = f"{CONTENT_PROJECTS_ROOT}/{pid}"

        if not Path(host).exists():
            print(f"WARN: host path does not exist for project '{pid}': {host} — skipping")
            skipped.append(pid)
            continue

        lines += [
            f"      - type: bind",
            f"        source: {host}",
            f"        target: {container}",
            f"        read_only: true",
        ]
        print(f"  + {pid}: {host} -> {container}")

    volumes_block = "\n".join(lines) if lines else "      []"
    content = (
        "# Auto-generated by scripts/gen_compose_mounts.py — do not edit manually.\n"
        "services:\n"
        "  rag-api:\n"
        "    volumes:\n"
        f"{volumes_block}\n"
    )

    OUT_FILE.write_text(content, encoding="utf-8")
    print(
        f"\nWritten {OUT_FILE.relative_to(ROOT)} "
        f"({len(lines) // 4} mount(s), {len(skipped)} skipped)"
    )


if __name__ == "__main__":
    main()
